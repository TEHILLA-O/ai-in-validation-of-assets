def _d(value: str) -> Decimal:
    return Decimal(value)


def _lines(raw: dict[str, str]) -> dict[str, Decimal]:
    return {key: _d(value) for key, value in raw.items()}


def _period(
    year: int,
    income: dict[str, str],
    balance: dict[str, str],
    cash_flow: dict[str, str],
) -> HistoricalPeriod:
    period = HistoricalPeriod(
        period_id=str(year),
        label=f"FY{year}A",
        year=year,
        period_end=date(year, 12, 31),
        days=365,
        currency="USD",
        income=_lines(income),
        balance=_lines(balance),
        cash_flow=_lines(cash_flow),
        statement_complete=True,
        accounting_basis="Synthetic accrual, US GAAP-like illustrative basis",
    )
    for key in list(period.income) + list(period.balance):
        period.sources[key] = SourceRef(
            source=SOURCE,
            reported_label=key,
            unit_scale="units",
            accounting_basis=period.accounting_basis,
            imported_at="2024-12-31T00:00:00Z",
        )
    return period


def _pct(rate: str) -> CostDriver:
    return CostDriver(method="pct_revenue", flat_pct=_d(rate))


